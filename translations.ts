export const getUITranslation = (langCode: string, key: string, variables?: Record<string, string>): string => {
  const map: Record<string, string> = {
    'gb': 'en', 'us': 'en', 'fr': 'fr', 'sa': 'ar', 'ar': 'ar', 'de': 'de', 'es': 'es', 'tr': 'tr', 'pt': 'pt'
  };
  const mappedLang = map[langCode] || 'en'; 
  
  const langTranslations = uiTranslations[mappedLang] || uiTranslations['en'];
  let translation = langTranslations[key] || uiTranslations['en'][key] || key;

  if (variables) {
    Object.entries(variables).forEach(([key, value]) => {
      translation = translation.replace(`{${key}}`, value);
    });
  }

  return translation;
};
